const fs = require('node:fs'), assert = require('node:assert/strict');
const {JSDOM} = require('../build/ui-test-tools/node_modules/jsdom');
const dom = new JSDOM(fs.readFileSync('web/index.html','utf8'),{url:'http://localhost',runScripts:'outside-only'});
const w=dom.window, d=w.document;
w.eval(fs.readFileSync('web/i18n.js','utf8'));
w.$=id=>d.getElementById(id); w.toast=()=>{}; w.hexGroup=String; w.esc=s=>String(s).replaceAll('<','&lt;');
w.renderByteEditor=el=>{el.innerHTML=Array.from({length:8},()=>'<input value="00">').join('');};
w.getByteHex=el=>[...el.querySelectorAll('input')].map(i=>i.value).join('');
w.setInterval=()=>{};
const calls=[];
const rule={id:'a',name:'删除',match_id:'123',data_contains:'12',data_cond:[{type:'byte',index:0,value:18}],data_cond_mode:'or',action:'send',send_id:'456',send_data:'1234',send_extended:false,enabled:true,hits:3};
w.api=async(path,method='GET',body)=>{calls.push({path,method,body});return method==='GET'?[rule]:{};};
const source=fs.readFileSync('web/app.js','utf8');
w.eval(source.slice(source.indexOf('let trConds = []'),source.indexOf('// ------------------------------------------------------------- 触发规则保存/读取')));
const tick=()=>new Promise(r=>setTimeout(r,0));
(async()=>{
  await w.refreshTriggers();
  w.trEdit('a'); w.trCondEdit(0);
  w.$('tc-v').value='AB';
  w.canI18n.setLanguage('en'); await tick();
  assert.equal(w.$('tc-v').value,'AB');
  assert.equal(w.$('tr-cond-mode').value,'or');
  assert.equal(w.$('tr-cond-type').value,'byte');
  assert.match(w.$('tr-cond-list').textContent,/OR/);
  assert.equal(w.$('btn-tr-cond-add').textContent,'Save condition changes');
  assert.equal(w.$('tr-name').value,'删除');
  w.$('btn-tr-cond-add').click(); await tick();
  await w.$('btn-tr-add').onclick(); await tick();
  const saved=calls.find(c=>c.method==='PUT');
  assert.equal(saved.body.data_cond[0].value,171);
  assert.equal(saved.body.data_cond_mode,'or');
  assert.equal(saved.body.name,'删除'); assert.equal(saved.body.send_data,'1234');
  assert.equal(saved.path,'/api/triggers/a');
  console.log('PASS: actual condition DOM edit + language switch + PUT retains values and rule identity');
  w.canI18n.dispose();w.close();
})().catch(e=>{console.error(e);w.canI18n.dispose();w.close();process.exitCode=1;});
